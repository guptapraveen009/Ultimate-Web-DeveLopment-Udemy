// JavaScript Events - Complete Notes with Explanation

// 1. Mouse Events
// • click – Occurs when an element is clicked.
// • dblclick – Occurs when an element is double-clicked.
// • mousedown – When mouse button is pressed down.
// • mouseup – When mouse button is released.
// • mousemove – When mouse moves over an element.
// • mouseover – When mouse enters an element.
// • mouseout – When mouse leaves an element.
// • mouseenter – Similar to mouseover but does not bubble.
// • mouseleave – Similar to mouseout but does not bubble.
// • contextmenu – When right-click menu opens.
// • wheel – When mouse wheel is rotated.


// 2. Keyboard Events
// • keydown – When a key is pressed down.
// • keyup – When a key is released.
// • keypress – When a key is pressed (deprecated).


// 3. Form Events
// • submit – When form is submitted.
// • reset – When form is reset.
// • change – When input value changes.
// • input – When user types in input field.
// • focus – When input field is selected.
// • blur – When input field loses focus.
// • select – When text is selected.
// • invalid – When input validation fails.


// 4. Window / Browser Events
// • load – When page fully loads.
// • DOMContentLoaded – When HTML is fully loaded.
// • beforeunload – Before leaving page.
// • unload – When page is closing.
// • resize – When window size changes.
// • scroll – When page is scrolled.
// • error – When error occurs.
// • hashchange – When URL hash changes.
// • online – When internet connection is restored.
// • offline – When internet connection is lost.
// • message – When message is received.
// • popstate – When browser history changes.


// 5. Clipboard Events
// • copy – When content is copied.
// • cut – When content is cut.
// • paste – When content is pasted.


// 6. Drag and Drop Events
// • drag – When element is dragged.
// • dragstart – When dragging starts.
// • dragend – When dragging ends.
// • dragenter – When dragged item enters target.
// • dragleave – When dragged item leaves target.
// • dragover – When dragged item is over target.
// • drop – When dragged item is dropped.


// 7. Media Events
// • play – When media starts playing.
// • pause – When media is paused.
// • ended – When media finishes.
// • volumechange – When volume changes.
// • timeupdate – When playback position changes.
// • loadeddata – When media data loads.
// • loadedmetadata – When metadata loads.
// • canplay – When media can start playing.
// • canplaythrough – When media can play fully.
// • waiting – When media is buffering.
// • seeking – When user starts seeking.
// • seeked – When seeking ends.


// 8. Touch Events
// • touchstart – When finger touches screen.
// • touchmove – When finger moves on screen.
// • touchend – When finger is removed.
// • touchcancel – When touch is interrupted.


// 9. Pointer Events
// • pointerdown – When pointer is pressed.
// • pointerup – When pointer is released.
// • pointermove – When pointer moves.
// • pointerover – When pointer enters element.
// • pointerout – When pointer leaves element.
// • pointerenter – Similar to pointerover (no bubbling).
// • pointerleave – Similar to pointerout (no bubbling).
// • pointercancel – When pointer is canceled.


// 10. Animation & Transition Events
// • animationstart – When animation starts.
// • animationend – When animation ends.
// • animationiteration – When animation repeats.
// • transitionstart – When transition starts.
// • transitionend – When transition ends.
// • transitionrun – When transition begins running.
// • transitioncancel – When transition is canceled.


// 11. Miscellaneous Events
// • toggle – When details element is opened/closed.
// • abort – When loading is stopped.
// • storage – When localStorage changes.
// • ratechange – When media playback rate changes.
// • durationchange – When media duration changes.
// • progress – When loading progress updates.
// • stalled – When media data is not available.
// • suspend – When media loading is stopped.